type Dict = { [k: string]: string | Dict };

/**
 * t('cart.title') → string, with {placeholder} interpolation.
 * Missing keys return the key itself (visible in dev, harmless in prod).
 */
export function t(key: string, params?: Record<string, string | number>): string {
  const parts = key.split('.');
  let node: string | Dict | undefined = it as unknown as Dict;
  for (const p of parts) {
    if (typeof node === 'object' && node !== null && p in node) {
      node = (node as Dict)[p];
    } else {
      return key;
    }
  }
  if (typeof node !== 'string') return key;
  if (!params) return node;
  return node.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m,
  );
}
